export function useBlueTaskCopy(): typeof en {
  const locale = useActiveLocale();
  if (locale === "ko") return ko;
  if (locale === "zh") return zh;
  if (locale === "es") return es;
  return en;
}

export function blueTaskStatusLabel(status: BlueTaskStatus, copy: typeof en): string {
  switch (status) {
    case "open":
      return copy.open;
    case "in_progress":
      return copy.inProgress;
    case "completed":
      return copy.completed;
    case "blocked":
      return copy.blocked;
  }
}

export function blueTaskPriorityLabel(priority: BlueTaskPriority, copy: typeof en): string {
  return copy[priority];
}
