// proxyEnv builds the Bash-subprocess env that routes child-command HTTP through
// the egress proxy (the recording MITM when capture is on, or the global proxy
// directly when it is off) and, only when a MITM CA is present, makes the common
// toolchain trust it — so tools need no manual -x/--proxy/-k. Each ecosystem reads
// a different CA var (verified empirically): SSL_CERT_FILE→curl/urllib/Go/openssl,
// REQUESTS_CA_BUNDLE→python requests (it ignores SSL_CERT_FILE), CURL_CA_BUNDLE→curl,
// GIT_SSL_CAINFO→git, NODE_EXTRA_CA_CERTS→node; NODE_USE_ENV_PROXY makes Node 24+
// honor the proxy vars. ALL_PROXY is set too so a socks5 egress proxy (which curl
// only reads from ALL_PROXY, not HTTP(S)_PROXY) works in the capture-off path.
// Empty proxyAddr → nil (direct, unchanged env).
func proxyEnv(proxyAddr, caCert string) []string {
	if proxyAddr == "" {
		return nil
	}
	env := []string{
		"HTTP_PROXY=" + proxyAddr, "HTTPS_PROXY=" + proxyAddr,
		"http_proxy=" + proxyAddr, "https_proxy=" + proxyAddr,
		"ALL_PROXY=" + proxyAddr, "all_proxy=" + proxyAddr, // socks5 egress: curl reads only this
		"NODE_USE_ENV_PROXY=1", // Node 24+: honor HTTP(S)_PROXY in built-in fetch/http
	}
	if caCert != "" {
		env = append(env,
			"SSL_CERT_FILE="+caCert,
			"CURL_CA_BUNDLE="+caCert,
			"REQUESTS_CA_BUNDLE="+caCert,
			"GIT_SSL_CAINFO="+caCert,
			"NODE_EXTRA_CA_CERTS="+caCert,
		)
	}
	return env
}

// workerDefaultTmpl is the built-in EDITABLE body (section [A]) of the worker system
// prompt, seeded into agent_prompts. The trafficTool block and artifact rules
// are NOT here — they are code-owned and appended by workerSystem after rendering
// (sections [B]/[C]), so editing the DB body can never drop them.
const workerDefaultTmpl = `You are the "worker" (work agent) in an authorized penetration-testing system on a cybersecurity platform. You receive **one intent**, a one-sentence exploration direction. Your only duty is to **complete that intent, write discoveries to the knowledge graph, then stop and return.**

**Boundaries:**
1. **Work only on the intent you received.** If you notice a lead outside that intent worth pursuing (a path leaked in an error, a possible connection to another asset, or an entry point for another exploitation chain), **mention it briefly in the fact's summary for the planner**.
2. An initial obstacle (filtered payload, 404, or no visible injection result) does not mean the direction is exhausted. Try all bypass approaches for this intent before concluding.
3. Act only within the authorized scope. If **operational constraints** appear at the top of the system prompt, they are highest-priority boundaries. Check every command or probe against them before running it; do not run anything that violates them, even if it fits the assigned intent.

**Write results as you find them.** Only graph entries count; thoughts and plain text do not. Record each result immediately so the turn budget does not expire before it is saved. Keep these three kinds of entries separate:
- **New asset/resource → insert_assets (asset graph):** register assets themselves, such as subdomains, services, endpoints, fingerprints, or credentials. **Register only assets here. Use record_fact for exploration conclusions or judgments.**
- **Exploration conclusion/fact → record_fact (exploration graph, with intent_id):** use this for all conclusions. **Combine multiple observations into one fact** with a one-sentence summary and a detail that expands it based on actual execution. Do not create one fact per attribute; an intent usually produces just one. Splitting everything would inflate the graph indefinitely. **Default to one fact and put related observations in detail.** Use the facts array for separate entries only for genuinely independent conclusions that cannot be combined; this is rare. **Record only new information:** do not rephrase existing facts as new ones. If this run merely confirms existing facts and adds nothing, no new fact is needed. **Record only what you actually observed:** include concise one-line evidence (the command and one or two most probative output lines; put other details in detail) and confidence (observed for direct observation, inferred for an inference from observed behavior).
- **Confirmed vulnerability → report_finding (exploration graph, with PoC and intent_id):** use this **only when you triggered the issue in this run and obtained reproducible evidence**, such as a request/response or command output. A version or fingerprint matching a CVE, a parameter that looks injectable, or an inference from an external vulnerability database, changelog, or code diff is not confirmation. Looking up CVEs or comparing patch versions cannot substitute for triggering the issue. If you suspect an issue but cannot trigger it, record one inferred fact (the suspicion and why it could not be triggered) for the planner; do not force it into a finding.

After completing the intent, summarize in one sentence what you did and which facts you wrote.`

// workerTrafficBlock is section [B]: the traffic-tool note, code-injected only when
// traffic capture (recording) is on — i.e. the traffic_* tools actually exist.
// Gated on recording, NOT on the egress proxy: a global proxy with capture off
// routes traffic but records nothing, so the tools would not be there. Not stored,
// not editable.
func workerTrafficBlock(recording bool) string {
	if !recording {
		return ""
	}
	return "\n\n**Traffic tools:**\n- traffic_search / traffic_get / traffic_blob: review responses and find previously visited resources. **Search recorded traffic first; do not curl the same URL again.** traffic_search **requires a host** and returns only three lightweight index entries by default (id/method/url/status/resp_len, no response body); increase limit explicitly for more. Use body_contains for full-text substring searches in request/response bodies (at least three characters; supports Chinese text too, such as searches for passwords, keys, errors, or internal addresses). To read a full record, use traffic_get(id). Very large bodies appear as @blob sha256:<hash>; use traffic_blob(hash) to retrieve the full text in chunks."
}

// artifactSpec is section [C]: the code-owned, non-editable tail appended to every
// pentest agent's prompt — intermediate artifacts must land in the shared work
// dir, never /tmp. Guaranteed present regardless of how the DB body is edited.
func artifactSpec(dir string) string {
	return "\n\n**Intermediate-artifact rules:** Write all scripts, payloads, captured response bodies, temporary data, and other intermediate artifacts **in this task's working directory: " + dir + "**. Relative paths resolve there; you may also use this absolute path. **Do not write to /tmp or any other absolute path.**"
}

// workerArtifactSpec is the worker's section [C]: its per-intent run dir is pre-created
// by the engine (ensureRunDir), so it just writes relative paths there — no manual
// mkdir, no cross-worker name collisions.
func workerArtifactSpec(runDir string) string {
	return "\n\n**Intermediate-artifact rules:** Write all scripts, payloads, captured response bodies, temporary data, and other intermediate artifacts **in this intent's dedicated working directory: " + runDir + "**. It already exists; write with relative paths and do not create it again. **Do not write to /tmp or any other absolute path.**"
}

// ensureRunDir builds and creates an agent's working directory under base:
// <base>/tasks/<taskID> for planner/main; <base>/tasks/<taskID>/i<intentID> for a
// worker (intentID<=0 → task dir only). The "tasks/" segment groups per-task dirs
// symmetrically with the chat agent's "sessions/<sessionID>". Best-effort mkdir — on
// failure, writes fail the same way an unwritable CWD would.
func ensureRunDir(base string, taskID, intentID int64) string {
	dir := filepath.Join(base, "tasks", strconv.FormatInt(taskID, 10))
	if intentID > 0 {
		dir = filepath.Join(dir, "i"+strconv.FormatInt(intentID, 10))
	}
	_ = os.MkdirAll(dir, 0o755)
	return dir
}

// cmdOutDir is the SDK large-tool-output spill dir under an agent's run dir.
func cmdOutDir(dir string) string { return filepath.Join(dir, "cmd-output") }

func workerSystem(proxyAddr, caCert, dataDir, runDir string) string {
	body := renderSystem("worker", workerDefaultTmpl, WorkerVars{ProxyAddr: proxyAddr, DataDir: dataDir, Now: nowStr()})
	// caCert is present only when the recording MITM is on, which is exactly when
	// the traffic_* tools are registered — so it gates the traffic-tool note.
	// Optional finding guidance is added for every role after tool resolution.
	return body + workerTrafficBlock(caCert != "") + workerArtifactSpec(runDir) + langDirective(resolveOutputLang())
}

// renderIntentTask formats the claimed intent for the worker's launch USER message:
// the intent is the worker's whole job. It used to live in the system prompt; it now
// rides in the first user turn (together with the situational overview) so the system
// prompt stays static/role-only — same move as the planner's situational block.
// intentAssetIDs pulls the intent's target asset ids out of its payload
// (planner's add_intent stores them as a numeric asset_ids array). nil on absence
// or malformed payload.
func intentAssetIDs(intent *db.Node) []int64 {
	if intent == nil {
		return nil
	}
	var p struct {
		AssetIDs []int64 `json:"asset_ids"`
	}
	if err := json.Unmarshal(intent.Payload, &p); err != nil {
		return nil
	}
	return p.AssetIDs
}

func renderIntentTask(intent *db.Node) string {
	return fmt.Sprintf("\n\nAssigned intent (your only task this run: do only this, record results, then stop):\n%s\nIntent ID: %d (pass it to record_fact / report_finding)", string(intent.Payload), intent.ID)
}

// renderWorkerGraphOverview folds the global situational snapshot into the worker's
// launch USER message for AWARENESS ONLY. The framing is deliberately strong: the overview
// must NOT widen the worker's job — it still does only its assigned intent. Its sole
// purpose is letting the worker read context (existing facts/assets/hints)
// so it avoids redundant work and doesn't re-derive what others already found.
func renderWorkerGraphOverview(data map[string]any) string {
	// Coverage tells the planner which classes have had little testing and whether
	// to expand scope. It conflicts with the worker's duty to follow only its
	// assigned intent, so omit it from the worker view. data is a new map for this
	// worker; deleting the key does not affect the planner.
	delete(data, "coverage")
	b, err := json.Marshal(data)
	if err != nil {
		return "" // fall back silently: the worker just won't have the global context
	}
	return "\n\nGlobal exploration overview (read-only context for your assigned intent):\n" +
		"The following is the current overview for the entire task. Use it to avoid repeating others' discoveries and to understand how your intent relates to the wider task.\n" +
		"**Think broadly while exploring this intent.** The boundary is that you must not execute another intent; the planner schedules that for other workers. If you notice a valuable lead (a cross-asset connection, an entry point for another exploitation chain, or a suspicious pattern at task level), **record it in a fact for the planner**. This is an important output. Report the lead for the planner to judge instead of keeping it to yourself.\n" +
		string(b)
}

// Execute runs one intent. hooks (the per-task Guard) gates every tool call; may
// be nil. emit, if non-nil, receives one ActivityRecord per execution step.
// notifyFinding, if non-nil, is called (intentID, summary) when this worker writes
// a finding (report_finding) so the task's planner wakes mid-flight — with context
// on which intent found what — instead of waiting for the worker to finish.
// Returns the terminal reason (so the engine can distinguish completed vs
// max_turns) and a per-kind breakdown of what was written back (so an intent that
// explored but persisted nothing isn't mistaken for done, and the engine can log
// facts/assets/findings separately instead of lumping them under "facts").
func (w *Worker) Execute(ctx context.Context, name string, taskID int64, as *db.AssetStore, ts *db.ExplorationStore, intent *db.Node, hooks harness.HookRunner, emit func(db.Activity), enr EnrichTrigger, notifyFinding func(int64, string)) (harness.TerminalReason, WriteCounts, error) {
	return w.execute(ctx, name, taskID, as, ts, intent, hooks, emit, enr, notifyFinding, "", "")
}

// ExecuteWithMessage runs the next turn in the same intent conversation with a
// human-authored message. The HTTP handler does not edit the transcript;
// agentcore records the message as a normal user turn when this Worker starts.
// This keeps Worker continuation identical to the regular agent chat flow.
func (w *Worker) ExecuteWithMessage(ctx context.Context, name string, taskID int64, as *db.AssetStore, ts *db.ExplorationStore, intent *db.Node, hooks harness.HookRunner, emit func(db.Activity), enr EnrichTrigger, notifyFinding func(int64, string), requestID, message string) (harness.TerminalReason, WriteCounts, error) {
	return w.execute(ctx, name, taskID, as, ts, intent, hooks, emit, enr, notifyFinding, strings.TrimSpace(requestID), strings.TrimSpace(message))
}

func (w *Worker) execute(ctx context.Context, name string, taskID int64, as *db.AssetStore, ts *db.ExplorationStore, intent *db.Node, hooks harness.HookRunner, emit func(db.Activity), enr EnrichTrigger, notifyFinding func(int64, string), requestID, message string) (harness.TerminalReason, WriteCounts, error) {
	tsx := NewToolSet(ts, name)
	tsx.SetFindingRecorder(w.findingRecorder)
	tsx.SetTaskID(taskID)
	coverageEnabled := as == nil || as.CoverageEnabled(taskID)
	tsx.SetCoverageEnabled(coverageEnabled)
	if as != nil {
		tsx.SetAssetStore(as, as.Companies())
	}
	tsx.SetOwnerNode(intent.ID)         // assets this worker discovers anchor to its intent → visible to the task
	tsx.SetEnrich(enr)                  // async DNS/HTTP auto-completion for assets this worker writes
	tsx.SetNotifyFinding(notifyFinding) // Wake planner when report_finding is saved, including intent and finding.
	// base = built-in worker tools ∪ host tools (traffic) ∪ default tools (incl. Bash);
	// then augment with the agent's visible skills/MCP. During the SDK settlement
	// phase, Bash is hidden via Settlement.DisabledTools (no local gating needed).
	base := append(tsx.WorkerTools(), w.extraTools...)
	// Omit MultiEdit/Glob/Grep: use Edit for precise changes and Bash (grep/find)
	// for searches. This narrows the tool set and reduces low-value calls. Other
	// SDK defaults (Read/Write/Edit/LS/Bash/Sleep) remain available.
	base = append(base, defaultToolsExcept("MultiEdit", "Glob", "Grep")...)
	ctx = WithRunInfo(ctx, RunInfo{TaskID: taskID, ExplorationID: explorationID(ts), IntentID: intent.ID})
	tools, def, cleanup := AugmentTools(ctx, "worker", base)
	defer cleanup()

	// The intent is the worker's sole duty throughout the run. Put it, the start
	// instruction, and raw data for its target assets in system. System is rebuilt
	// each run and survives compaction, so long or resumed runs retain the intent
	// even if the first transcript message is lost. Per-intent data reduces caching
	// across intents, an intentional trade-off. Unlike the planner, the worker has
	// one mandate. Only the global overview goes in the starting user message; it
	// can become stale or be compacted without losing the mandate. The engine
	// pre-creates <workDir>/tasks/<taskID>/i<intentID> for this intent.
	runDir := ensureRunDir(w.workDir, taskID, intent.ID)
	// The run-wide intent is not the current tool action. Do not forward it or
	// inherit a parent run's background into the action reviewer.
	ctx = intercept.WithReviewContext(ctx, runDir, intercept.ReviewBackground{})
	overview := renderWorkerGraphOverview(tsx.graphOverviewData())
	sysBody := workerSystem(w.proxyAddr, w.proxyCACert, w.workDir, runDir)
	if w.wantConstraints() {
		sysBody += constraintBlock(ts) // Inject operational constraints into system for worker compliance.
	}
	// Append intent, target assets, then start instruction to system (as with constraintBlock).
	sysBody += renderIntentTask(intent)
	if as != nil {
		if ids := intentAssetIDs(intent); len(ids) > 0 {
			if assets, err := as.GetByIDs(ids); err == nil && len(assets) > 0 {
				if b, err := json.Marshal(assets); err == nil {
					sysBody += "\n\nTarget assets corresponding to this intent's asset_ids:\n" + string(b)
				}
				// Add explicitly targeted assets to task test scope at the same
				// conservative granularity as insertAssets. upsertTaskScope's
				// ON CONFLICT DO NOTHING and uq_task_scope index prevent duplicates,
				// including reruns/retries. Do not grow the denominator when coverage
				// is disabled.
				if coverageEnabled {
					for _, a := range assets {
						_ = as.AddAutoScope(taskID, a.Type, a.Domain, a.URL, a.IP)
					}
				}
			}
		}
	}
	sysBody += "\n\nExecute the assigned intent now. Work only on it; record facts, assets, and findings, then stop."
	system, boundary := deferredSystem(sysBody, def)
	// The task deadline from ctx caps this run's wall-clock budget and selects wrap-up wording.
	tc := taskClockFrom(ctx)
	maxDur, clamped := clampMaxDuration(tc.DeadlineUnix, w.runTimeout)
	settle := wrapupSettlement("worker", []string{"Bash"})
	if tc.DeadlineUnix > 0 {
		settle = wrapupSettlementForTask("worker", []string{"Bash"}, clamped)
	}
	opts := agentcore.Options{
		Provider:        w.prov,
		SystemPrompt:    system,
		DynamicBoundary: boundary,
		Tools:           tools,
		DeferredTools:   def.Deferred,
		UnlockSet:       def.Unlock,
		PermissionMode:  permission.ModeBypass,
		// WebFetch uses the recording proxy, so its HTTP is captured like curl.
		// Load the proxy CA so MITM re-signed HTTPS certificates validate normally.
		// An empty proxy means direct access.
		EnableWebFetch: true,
		WebFetchProxy:  w.proxyAddr,
		WebFetchCACert: w.proxyCACert,
		// Optional web search: ddgs needs no key; brave-free needs BraveKey; tavily needs TavilyKey.
		// WebSearchProxy is a separate egress proxy (http/https/socks5); empty means direct.
		EnableWebSearch:       w.webSearch.Enabled,
		WebSearchBackend:      w.webSearch.Backend,
		BraveSearchAPIKey:     w.webSearch.BraveKey,
		TavilySearchAPIKey:    w.webSearch.TavilyKey,
		DeepSeekSearchBaseURL: w.webSearch.DeepSeekBaseURL,
		DeepSeekSearchAPIKey:  w.webSearch.DeepSeekAPIKey,
		DeepSeekSearchModel:   w.webSearch.DeepSeekModel,
		WebSearchProxy:        w.webSearch.Proxy,
		// Bash subprocess HTTP uses the recording proxy and trusts its CA (no -x/-k needed).
		BashEnv:    proxyEnv(w.proxyAddr, w.proxyCACert),
		WorkingDir: runDir,
		MaxTurns:   w.maxTurns, // 0 = unlimited (configurable in agent management)
		// Wall-clock budget, checked at turn boundaries without mid-turn interruption;
		// 0 = unlimited. Cap it by the remaining task deadline when present so this
		// run enters wrap-up when the task expires (see taskclock.go).
		MaxDuration: maxDur,
		// On turn or time budget exhaustion, the SDK runs a wrap-up turn without
		// Bash to save identified results. When clamped by task deadline, use
		// PromptByReason: task-timeout wording for elapsed time, per-run wording if
		// turns run out first. Otherwise keep per-run wording.
		Settlement: settle,
		// large tool output spills to cmd-output/ with a head + pointer (SDK tool.Capture);
		// Full output is preserved on disk. Use the SDK's default 30,000-character truncation limit.
		ToolOutputDir: cmdOutDir(runDir),
		Compaction:    compactionConfig(w.compactionWindow()), // long tool-heavy runs stay within the window
		Todos:         actool.NewTodoStore(),                  // Session-only TodoWrite notes; discarded on exit.
		NonStreaming:  w.nonStreaming(),                       // Use Provider.Complete for a non-streaming profile.
		MaxTokens:     w.maxTokens(),                          // 0 = omit the cap and use the server default.
	}
	if hooks != nil { // typed-nil guard: only set when concrete (avoids harness panic)
		opts.Hooks = hooks
	}
	if w.tx != nil { // persist raw LLM conversation; one file per worked intent
		opts.Transcript = w.tx
		opts.SessionID = WorkerSessionID(ts.ID(), intent.ID)
	}
	intentID := intent.ID
	emitWrap := func(r db.Activity) {
		if emit != nil {
			r.NodeID, r.Worker = &intentID, name
			emit(r)
		}
	}
	// System already carries the intent, start instruction, and target assets.
	// The starting user message carries only the global overview, which can be
	// compacted. If marshaling the overview fails, use a nonempty start message.
	input := overview
	if strings.TrimSpace(input) == "" {
		input = "Execute the intent assigned in system. Work only on it; record facts, assets, and findings, then stop."
	}

	// Experimental noa compaction keeps persistent archives under <workDir>/noa/<SessionID>.
	noaSession := WorkerSessionID(ts.ID(), intent.ID)
	enableNoa(&opts, w.noaEnabledFn, w.workDir, noaSession, noaWarn(noaSession))
	ctx = attachSideCapture(ctx, &opts)
	s := agentcore.NewSession(opts)
	defer s.Close() // release the session's background-task manager (temp dir + processes)

	// Resume prior conversation if this intent was paused/blocked/exhausted and is
	// being re-run. The transcript ID is deterministic per intent, so if a prior
	// session exists the worker continues from where it left off instead of
	// restarting from scratch.
	alreadyRecorded := false
	if w.tx != nil {
		_ = s.Resume(opts.SessionID)
		alreadyRecorded = requestID != "" && hasWorkerChatMessage(s.Messages(), requestID)
		if len(s.Messages()) > 0 && message == "" {
			seedUnlockFromHistory(s.Messages(), def.UnlockSkill)
			input = "Continue execution."
		} else if len(s.Messages()) > 0 {
			seedUnlockFromHistory(s.Messages(), def.UnlockSkill)
		}
	}
	if message != "" {
		if alreadyRecorded {
			input = "Continue the new intent from the previous human chat message. Do not repeat completed actions."
		} else if len(s.Messages()) > 0 {
			input = workerChatMarker(requestID) + "\nNew intent from human chat:\n" + message +
				"\n\nExecute this human request immediately. Afterward, use the context to decide whether to continue the original task."
		} else {
			input += "\n\n" + workerChatMarker(requestID) + "\nNew intent from human chat:\n" + message +
				"\n\nPrioritize this human request."
		}
	}

	// Budgets + settlement are owned by the SDK (MaxTurns/MaxDuration + Settlement):
	// on hit it runs a wrap-up turn and finishes with ReasonMaxTurns/ReasonTimeout.
	// MaxDuration now interrupts an in-flight tool at the wall-clock deadline and
	// enters the wrap-up phase on the live ctx, so a run whose tool overran the budget
	// still settles (no external hard-timeout backstop needed). ctx itself carries only
	// pause / planner kill / shutdown, which the engine distinguishes and re-queues/stops.
	_, reason, err := captureRunSession(ctx, s, input, emitWrap)
	return reason, tsx.Writes(), err
}
